/// <summary>Writes invoices and receipts as PDF. Internal staff notes are never included.</summary>
public sealed class PdfDocumentWriter : IDocumentPdfWriter
{
    public Task WriteInvoiceAsync(string path, InvoiceDocument d, CancellationToken ct = default) => Task.Run(() =>
    {
        var cf = d.Currency;
        using var pdf = new PdfBuilder($"Invoice {d.Number}");
        Header(pdf, d.BusinessName, d.BusinessAddress, d.BusinessPhone, d.BusinessEmail, "INVOICE", d.Number);
        if (d.IsDemo) pdf.Line("DEMO WORKSPACE — sample document with fictional data", 9, true, PdfBuilder.Muted);
        if (d.Status == InvoiceStatus.Void) pdf.Line("VOID — this invoice has been superseded", 11, true, XColor.FromArgb(0xE4, 0x56, 0x62));

        pdf.Line("Bill to", 9, true, PdfBuilder.Muted);
        pdf.Line(d.CustomerName, 11, true);
        if (!string.IsNullOrWhiteSpace(d.CustomerEmail)) pdf.Line(d.CustomerEmail!, 9, false, PdfBuilder.Muted);
        if (!string.IsNullOrWhiteSpace(d.CustomerPhone)) pdf.Line(d.CustomerPhone!, 9, false, PdfBuilder.Muted);
        pdf.Y += 6;
        pdf.Line($"Issued: {d.IssuedAt:MMMM d, yyyy}    Appointment: #{d.AppointmentReference} on {d.AppointmentStart:MMMM d, yyyy h:mm tt}    Status: {Status(d.Status)}", 9, false, PdfBuilder.Muted);
        pdf.Y += 8;

        pdf.Table(["Service", "Staff", "Qty", "Unit price", "Discount", "Amount"],
            d.Lines.Select(l => (IReadOnlyList<string>)[l.Description, l.StaffName ?? "", l.Quantity.ToString(CultureInfo.InvariantCulture),
                cf.Format(l.UnitPriceMinor), l.DiscountMinor == 0 ? "—" : "-" + cf.Format(l.DiscountMinor), cf.Format(l.LineTotalMinor)]).ToList(),
            [3.2, 2, 0.7, 1.5, 1.4, 1.6], [false, false, true, true, true, true]);

        Totals(pdf,
        [
            ("Subtotal", cf.Format(d.SubtotalMinor), false),
            ("Discounts", d.DiscountMinor == 0 ? cf.Format(0) : "-" + cf.Format(d.DiscountMinor), false),
            ($"{d.TaxLabel} ({d.TaxRateBasisPoints / 100.0:0.##}%)", cf.Format(d.TaxMinor), false),
            ("Total", cf.Format(d.TotalMinor), true),
            ("Amount paid", cf.Format(d.PaidMinor), false),
            ("Balance due", cf.Format(d.BalanceMinor), true),
        ]);

        if (d.Payments.Count > 0)
        {
            pdf.Y += 10;
            pdf.Line("Payments", 10, true);
            pdf.Table(["Receipt", "Date", "Type", "Method", "Amount"],
                d.Payments.Select(p => (IReadOnlyList<string>)[p.Reference, p.Date.ToString("MMM d, yyyy h:mm tt", CultureInfo.InvariantCulture), p.Kind, p.Method, cf.Format(p.SignedAmountMinor)]).ToList(),
                [1.6, 2, 1.1, 2, 1.4], [false, false, false, false, true]);
        }

        if (!string.IsNullOrWhiteSpace(d.CustomerNotes))
        {
            pdf.Y += 6;
            pdf.Line("Notes", 9, true, PdfBuilder.Muted);
            pdf.Line(d.CustomerNotes!, 9);
        }

        pdf.Rule(12);
        pdf.Line(d.Footer, 9, false, PdfBuilder.Muted);
        pdf.Line("This document is a commercial invoice/receipt generated by ScheduleOS. It is not a jurisdiction-specific tax invoice.", 7.5, false, PdfBuilder.Muted);
        pdf.Save(path);
    }, ct);

    public Task WriteReceiptAsync(string path, ReceiptDocument d, CancellationToken ct = default) => Task.Run(() =>
    {
        var cf = d.Currency;
        using var pdf = new PdfBuilder($"Receipt {d.ReceiptNumber}");
        Header(pdf, d.BusinessName, d.BusinessAddress, null, null, d.Kind.ToUpperInvariant() + " RECEIPT", d.ReceiptNumber);
        pdf.Line($"Customer: {d.CustomerName}", 11, true);
        if (d.AppointmentReference is not null) pdf.Line($"Appointment: #{d.AppointmentReference}", 10);
        pdf.Line($"Date: {d.RecordedAt:MMMM d, yyyy h:mm tt}", 10);
        pdf.Line($"Method: {d.Method}", 10);
        if (!string.IsNullOrWhiteSpace(d.ExternalReference)) pdf.Line($"Reference: {d.ExternalReference}", 10);
        if (!string.IsNullOrWhiteSpace(d.Note)) pdf.Line($"Note: {d.Note}", 10);
        if (!string.IsNullOrWhiteSpace(d.RecordedBy)) pdf.Line($"Recorded by: {d.RecordedBy}", 10, false, PdfBuilder.Muted);
        pdf.Y += 8;
        Totals(pdf,
        [
            ("Amount", cf.Format(d.AmountMinor), true),
            ("Appointment total", cf.Format(d.AppointmentTotalMinor), false),
            ("Paid to date", cf.Format(d.AppointmentPaidMinor), false),
            ("Remaining balance", cf.Format(d.AppointmentTotalMinor - d.AppointmentPaidMinor), false),
        ]);
        pdf.Rule(12);
        pdf.Line("Card payments are processed on an external terminal and recorded manually in ScheduleOS.", 7.5, false, PdfBuilder.Muted);
        pdf.Save(path);
    }, ct);

    private static void Header(PdfBuilder pdf, string business, string? address, string? phone, string? email, string title, string number)
    {
        pdf.Fill(0, 0, pdf.Right + PdfBuilder.Margin, 6, PdfBuilder.Teal);
        var y = pdf.Y;
        pdf.Text(business, PdfBuilder.Font(18, true), PdfBuilder.Navy, pdf.Left, pdf.Width / 2);
        pdf.Text(title, PdfBuilder.Font(18, true), PdfBuilder.Teal, pdf.Left + pdf.Width / 2, pdf.Width / 2, XStringFormats.TopRight);
        pdf.Y += 26;
        pdf.Text(number, PdfBuilder.Font(10), PdfBuilder.Muted, pdf.Left + pdf.Width / 2, pdf.Width / 2, XStringFormats.TopRight);
        foreach (var line in new[] { address, phone, email }.Where(l => !string.IsNullOrWhiteSpace(l)))
        {
            pdf.Text(line!, PdfBuilder.Font(9), PdfBuilder.Muted, pdf.Left, pdf.Width / 2);
            pdf.Y += 13;
        }

        pdf.Y = Math.Max(pdf.Y, y + 44);
        pdf.Rule(4, 12);
    }

    private static void Totals(PdfBuilder pdf, IEnumerable<(string Label, string Value, bool Bold)> rows)
    {
        var x = pdf.Left + pdf.Width * 0.55;
        var w = pdf.Width * 0.45;
        foreach (var (label, value, bold) in rows)
        {
            pdf.EnsureSpace(18);
            pdf.Text(label, PdfBuilder.Font(10, bold), bold ? PdfBuilder.Navy : PdfBuilder.Muted, x, w / 2);
            pdf.Text(value, PdfBuilder.Font(10, bold), PdfBuilder.Navy, x + w / 2, w / 2, XStringFormats.TopRight);
            pdf.Y += 17;
        }
    }

    private static string Status(InvoiceStatus s) => s switch
    {
        InvoiceStatus.PartiallyPaid => "Partially paid",
        _ => s.ToString(),
    };
}

/// <summary>Exports report tables to CSV, XLSX (ClosedXML, MIT) and PDF (PDFsharp, MIT).</summary>
public sealed class ReportExporter : IReportExporter
{
    public async Task ExportCsvAsync(string path, IReadOnlyList<TabularReport> reports, CancellationToken ct = default)
    {
        var sb = new StringBuilder();
        foreach (var report in reports)
        {
            sb.AppendLine(Escape(report.Title));
            sb.AppendLine(string.Join(",", report.Columns.Select(Escape)));
            foreach (var row in report.Rows) sb.AppendLine(string.Join(",", row.Select(v => Escape(Format(v)))));
            sb.AppendLine();
        }

        await File.WriteAllTextAsync(path, sb.ToString(), new UTF8Encoding(true), ct);
    }

    public Task ExportXlsxAsync(string path, IReadOnlyList<TabularReport> reports, CancellationToken ct = default) => Task.Run(() =>
    {
        using var wb = new XLWorkbook();
        var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var report in reports)
        {
            var name = new string(report.Title.Where(c => !"[]*?/\\:".Contains(c)).ToArray());
            name = name.Length > 31 ? name[..31] : name;
            for (var i = 2; !used.Add(name); i++) name = $"{name[..Math.Min(name.Length, 28)]} {i}";
            var ws = wb.Worksheets.Add(name);
            for (var c = 0; c < report.Columns.Count; c++)
            {
                var cell = ws.Cell(1, c + 1);
                cell.Value = report.Columns[c];
                cell.Style.Font.Bold = true;
                cell.Style.Fill.BackgroundColor = XLColor.FromHtml("#DDF5F2");
            }

            for (var r = 0; r < report.Rows.Count; r++)
            for (var c = 0; c < report.Rows[r].Count; c++)
            {
                var v = report.Rows[r][c];
                var cell = ws.Cell(r + 2, c + 1);
                switch (v)
                {
                    case int i: cell.Value = i; break;
                    case long l: cell.Value = l; break;
                    case double d: cell.Value = d; break;
                    case decimal m: cell.Value = m; break;
                    case string s when decimal.TryParse(s, NumberStyles.AllowLeadingSign | NumberStyles.AllowDecimalPoint, CultureInfo.InvariantCulture, out var num):
                        cell.Value = num;
                        break;
                    default: cell.Value = Format(v); break;
                }
            }

            ws.Columns().AdjustToContents(1, Math.Min(report.Rows.Count + 1, 500));
            ws.SheetView.FreezeRows(1);
        }

        wb.SaveAs(path);
    }, ct);

    public Task ExportPdfAsync(string path, string title, string subtitle, IReadOnlyList<TabularReport> reports, CancellationToken ct = default) => Task.Run(() =>
    {
        using var pdf = new PdfBuilder(title);
        pdf.Line(title, 18, true);
        pdf.Line(subtitle, 10, false, PdfBuilder.Muted);
        pdf.Rule();
        foreach (var report in reports)
        {
            pdf.EnsureSpace(60);
            pdf.Line(report.Title, 12, true, PdfBuilder.Teal);
            var weights = report.Columns.Select((_, i) => i == 0 ? 2.0 : 1.0).ToArray();
            var right = report.Columns.Select((_, i) => i > 0).ToArray();
            pdf.Table(report.Columns, report.Rows.Select(r => (IReadOnlyList<string>)r.Select(Format).ToList()).ToList(), weights, right, 8);
            pdf.Y += 8;
        }

        pdf.Save(path);
    }, ct);

    private static string Format(object? v) => v switch
    {
        null => "",
        DateTime d => d.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture),
        IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
        _ => v.ToString() ?? "",
    };

    private static string Escape(string s)
    {
        if (s.Length > 0 && "=+-@".Contains(s[0]) && !decimal.TryParse(s, NumberStyles.Number, CultureInfo.InvariantCulture, out _))
            s = "'" + s; // neutralise spreadsheet formula injection
        return s.IndexOfAny([',', '"', '\n', '\r']) >= 0 ? "\"" + s.Replace("\"", "\"\"") + "\"" : s;
    }
}
